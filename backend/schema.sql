-- kwetucreations enquiry intake
-- Run once with:  php backend/setup-database.php
-- or paste into phpMyAdmin's SQL tab.

CREATE DATABASE IF NOT EXISTS kwetu_testimonials
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE kwetu_testimonials;

-- One row per testimonial a client submits. Nothing reaches the website
-- until status is 'approved' in the review screen.
CREATE TABLE IF NOT EXISTS testimonial_submissions (
    id                  INT UNSIGNED NOT NULL AUTO_INCREMENT,
    client_name         VARCHAR(100) NOT NULL,
    business_name       VARCHAR(150) NULL,
    rating              TINYINT UNSIGNED NOT NULL,
    testimonial         TEXT         NOT NULL,

    -- A row can never be approved while this is 0: publication permission is
    -- checked again at approval time, not only at submit time.
    publication_consent TINYINT(1)   NOT NULL DEFAULT 0,

    status              ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',

    -- The visitor's IP address is never stored. This is SHA-256 of the IP
    -- with the installation's private ip_salt, so repeat submissions can be
    -- rate-limited without keeping a traceable address.
    ip_hash             CHAR(64)     NOT NULL,

    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at         TIMESTAMP    NULL DEFAULT NULL,
    reviewed_status_note VARCHAR(255) NULL DEFAULT NULL,

    PRIMARY KEY (id),
    KEY idx_status_created (status, created_at),
    KEY idx_created_ip (created_at, ip_hash),
    KEY idx_consent_status (publication_consent, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Contact and quote submissions. These are private correspondence, not
-- publishable content, so there is no 'approved' state — only whether a
-- person has dealt with it yet.
CREATE TABLE IF NOT EXISTS enquiries (
    id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    kind        ENUM('contact','quote') NOT NULL,

    full_name   VARCHAR(120) NOT NULL,
    business    VARCHAR(150) NULL,
    email       VARCHAR(190) NOT NULL,
    phone       VARCHAR(40)  NULL,
    address     VARCHAR(250) NULL,

    -- "What is your enquiry about?" on the contact form, "Service required"
    -- on the quote form. Only the fixed list of options is accepted.
    topic       VARCHAR(60)  NULL,
    message     TEXT         NOT NULL,

    status      ENUM('new','handled','archived') NOT NULL DEFAULT 'new',

    -- Same reasoning as testimonial_submissions: a fingerprint, never an address.
    ip_hash     CHAR(64)     NOT NULL,

    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP    NULL DEFAULT NULL,
    reply_note  VARCHAR(255) NULL DEFAULT NULL,

    PRIMARY KEY (id),
    KEY idx_status_created (status, created_at),
    KEY idx_kind_created (kind, created_at),
    KEY idx_created_ip (created_at, ip_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Design files a client attached to a quote request. The bytes live in
-- backend/storage/, which is refused over HTTP; this table only records where
-- they are and what they were claimed to be.
CREATE TABLE IF NOT EXISTS enquiry_files (
    id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
    enquiry_id     INT UNSIGNED NOT NULL,

    -- Generated by the server (random hex + vetted extension). The name the
    -- browser sent is never used for the path on disk.
    stored_name    CHAR(45)     NOT NULL,

    -- Display only, and escaped wherever it is shown.
    original_name  VARCHAR(255) NOT NULL,

    -- What the server detected from the bytes, not what the client claimed.
    detected_type  VARCHAR(100) NOT NULL,
    size_bytes     INT UNSIGNED NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),
    KEY idx_enquiry (enquiry_id),
    CONSTRAINT fk_enquiry_file FOREIGN KEY (enquiry_id)
        REFERENCES enquiries (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Failed sign-in attempts against the review screens, one row per address
-- fingerprint. This exists because the lockout has to survive someone closing
-- their cookies: a session counter only stops a polite script.
CREATE TABLE IF NOT EXISTS admin_login_attempts (
    ip_hash CHAR(64) NOT NULL,
    hits INT UNSIGNED NOT NULL DEFAULT 1,
    window_started_at DATETIME NOT NULL,
    locked_until DATETIME NULL DEFAULT NULL,
    PRIMARY KEY (ip_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
